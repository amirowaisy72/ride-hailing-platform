
"use client";

import { useCallback, useEffect, useState } from "react";
import {
    CheckCircle2, XCircle, FileCheck2, Eye,
    RefreshCw, X, AlertTriangle, ShieldCheck,
} from "lucide-react";
import { authenticatedAdminRequest } from "@/lib/adminSession";
import { useAdminDialog } from "@/components/AdminDialog";

const requiredTypes = [
    "CNIC_FRONT",
    "CNIC_BACK",
    "DRIVING_LICENSE",
    "VEHICLE_REGISTRATION",
];

const labels = {
    CNIC_FRONT: "CNIC — Front",
    CNIC_BACK: "CNIC — Back",
    DRIVING_LICENSE: "Driving License",
    VEHICLE_REGISTRATION: "Vehicle Registration",
};

export default function DriverDocumentReview({
    driverId,
    driverName,
    onClose,
    onUpdated,
}) {
    const { confirmDialog } = useAdminDialog();
    const [documents, setDocuments] = useState([]);
    const [loading, setLoading] = useState(true);
    const [busyId, setBusyId] = useState(null);
    const [error, setError] = useState("");
    const [message, setMessage] = useState("");
    const [preview, setPreview] = useState(null);
    const [previewLoading, setPreviewLoading] = useState(false);
    const [rejectionId, setRejectionId] = useState(null);
    const [rejectionReason, setRejectionReason] = useState("");

    const loadDocuments = useCallback(async () => {
        if (!driverId) return;

        setLoading(true);
        setError("");

        try {
            const result = await authenticatedAdminRequest(
                `/admin/drivers/${encodeURIComponent(driverId)}/documents`
            );
            setDocuments(result.documents || []);
        } catch (err) {
            setError(err.message);
        } finally {
            setLoading(false);
        }
    }, [driverId]);

    useEffect(() => {
        loadDocuments();
    }, [loadDocuments]);

    async function viewDocument(documentId) {
        setPreviewLoading(true);
        setError("");
        setPreview(null);

        try {
            const result = await authenticatedAdminRequest(
                `/admin/drivers/documents/${encodeURIComponent(documentId)}/view`
            );

            // URL is generated by the authenticated backend.
            setPreview({
                url: result.imageUrl,
                expiresIn: result.expiresIn,
            });
        } catch (err) {
            setError(err.message);
        } finally {
            setPreviewLoading(false);
        }
    }

    async function reviewDocument(documentId, status, reason = "") {
        if (busyId) return;

        setBusyId(documentId);
        setError("");
        setMessage("");

        try {
            await authenticatedAdminRequest(
                `/admin/drivers/documents/${encodeURIComponent(documentId)}/review`,
                {
                    method: "PATCH",
                    body: JSON.stringify({
                        status,
                        ...(status === "REJECTED"
                            ? { rejectionReason: reason.trim() }
                            : {}),
                    }),
                }
            );

            setMessage(
                status === "APPROVED"
                    ? "Document approved successfully."
                    : "Document rejected successfully."
            );

            setRejectionId(null);
            setRejectionReason("");
            setPreview(null);

            await loadDocuments();
            onUpdated?.();
        } catch (err) {
            setError(err.message);
        } finally {
            setBusyId(null);
        }
    }

    const approvedTypes = new Set(
        documents
            .filter((doc) => doc.verificationStatus === "APPROVED")
            .map((doc) => doc.documentType)
    );

    const readyForApproval = requiredTypes.every((type) =>
        approvedTypes.has(type)
    );

    return (
        <div className="fixed inset-0 z-[100] flex items-center justify-center bg-slate-950/60 p-3 sm:p-6">
            <section
                role="dialog"
                aria-modal="true"
                aria-label="Driver document verification"
                className="flex max-h-[92vh] w-full max-w-3xl flex-col overflow-hidden rounded-[26px] bg-white shadow-2xl"
            >
                <header className="flex items-start justify-between gap-4 border-b p-5 sm:p-6">
                    <div>
                        <p className="text-xs font-bold uppercase tracking-wider text-[#087F5B]">
                            Driver Verification
                        </p>
                        <h2 className="mt-1 text-xl font-extrabold">
                            Review Documents
                        </h2>
                        <p className="mt-1 text-sm text-slate-500">
                            {driverName || "Driver"}
                        </p>
                    </div>

                    <button
                        type="button"
                        onClick={onClose}
                        aria-label="Close document review"
                        className="rounded-xl bg-slate-100 p-3"
                    >
                        <X size={20} />
                    </button>
                </header>

                <div className="space-y-5 overflow-y-auto p-5 sm:p-6">
                    <div className={`rounded-2xl p-4 ${readyForApproval
                            ? "bg-emerald-50 text-[#065F46]"
                            : "bg-amber-50 text-amber-800"
                        }`}>
                        <div className="flex items-center gap-2 font-bold">
                            {readyForApproval
                                ? <ShieldCheck size={20} />
                                : <AlertTriangle size={20} />}
                            {readyForApproval
                                ? "Required Documents Approved"
                                : "Verification Incomplete"}
                        </div>
                        <p className="mt-2 text-sm">
                            {approvedTypes.size} approved document types recorded.
                            All four required document types must be approved
                            before driver approval.
                        </p>
                    </div>

                    {error && (
                        <p role="alert" className="rounded-xl bg-red-50 p-4 text-sm text-red-600">
                            {error}
                        </p>
                    )}

                    {message && (
                        <p role="status" className="rounded-xl bg-emerald-50 p-4 text-sm text-[#065F46]">
                            {message}
                        </p>
                    )}

                    <div className="flex items-center justify-between">
                        <h3 className="font-extrabold">Uploaded Documents</h3>
                        <button
                            type="button"
                            onClick={loadDocuments}
                            disabled={loading}
                            className="flex items-center gap-2 text-sm font-bold text-[#087F5B]"
                        >
                            <RefreshCw size={16} />
                            Refresh
                        </button>
                    </div>

                    {loading ? (
                        <p className="py-8 text-center text-sm text-slate-500">
                            Loading documents...
                        </p>
                    ) : documents.length === 0 ? (
                        <p className="rounded-2xl bg-slate-50 p-8 text-center text-sm text-slate-500">
                            No documents uploaded yet.
                        </p>
                    ) : (
                        <div className="space-y-3">
                            {documents.map((doc) => {
                                const pending =
                                    doc.verificationStatus !== "APPROVED" &&
                                    doc.verificationStatus !== "REJECTED";

                                return (
                                    <div
                                        key={doc._id}
                                        className="rounded-2xl border border-slate-200 p-4"
                                    >
                                        <div className="flex flex-wrap items-center gap-3">
                                            <div className="rounded-xl bg-emerald-50 p-3 text-[#087F5B]">
                                                <FileCheck2 size={22} />
                                            </div>

                                            <div className="min-w-0 flex-1">
                                                <p className="font-bold">
                                                    {labels[doc.documentType] || doc.documentType}
                                                </p>
                                                <p className="mt-1 text-xs text-slate-500">
                                                    {doc.verificationStatus}
                                                </p>
                                            </div>

                                            <button
                                                type="button"
                                                onClick={() => viewDocument(doc._id)}
                                                disabled={previewLoading}
                                                className="flex items-center gap-2 rounded-xl border px-3 py-2 text-sm font-semibold disabled:opacity-50"
                                            >
                                                <Eye size={16} />
                                                View
                                            </button>
                                        </div>

                                        {doc.rejectionReason && (
                                            <p className="mt-3 rounded-xl bg-red-50 p-3 text-xs text-red-700">
                                                Reason: {doc.rejectionReason}
                                            </p>
                                        )}

                                        {pending && (
                                            <div className="mt-4 flex flex-wrap gap-2">
                                                <button
                                                    type="button"
                                                    disabled={Boolean(busyId)}
                                                    onClick={async () => {
                                                        if (await confirmDialog("Approve this document?")) {
                                                            reviewDocument(doc._id, "APPROVED");
                                                        }
                                                    }}
                                                    className="flex items-center gap-2 rounded-xl bg-[#087F5B] px-4 py-2.5 text-sm font-bold text-white disabled:opacity-50"
                                                >
                                                    <CheckCircle2 size={16} />
                                                    Approve
                                                </button>

                                                <button
                                                    type="button"
                                                    disabled={Boolean(busyId)}
                                                    onClick={() => {
                                                        setRejectionId(doc._id);
                                                        setRejectionReason("");
                                                    }}
                                                    className="flex items-center gap-2 rounded-xl border border-red-200 px-4 py-2.5 text-sm font-bold text-red-600 disabled:opacity-50"
                                                >
                                                    <XCircle size={16} />
                                                    Reject
                                                </button>
                                            </div>
                                        )}

                                        {rejectionId === doc._id && (
                                            <div className="mt-4 space-y-3 rounded-xl bg-red-50 p-4">
                                                <label className="block text-sm font-bold">
                                                    Rejection Reason
                                                </label>
                                                <textarea
                                                    value={rejectionReason}
                                                    onChange={(e) => setRejectionReason(e.target.value)}
                                                    maxLength={500}
                                                    rows={3}
                                                    placeholder="Explain why this document is rejected"
                                                    className="w-full rounded-xl border p-3 text-sm outline-none"
                                                />
                                                <div className="flex gap-2">
                                                    <button
                                                        type="button"
                                                        disabled={!rejectionReason.trim() || Boolean(busyId)}
                                                        onClick={() =>
                                                            reviewDocument(doc._id, "REJECTED", rejectionReason)
                                                        }
                                                        className="rounded-xl bg-red-600 px-4 py-2.5 text-sm font-bold text-white disabled:opacity-50"
                                                    >
                                                        Confirm Rejection
                                                    </button>
                                                    <button
                                                        type="button"
                                                        onClick={() => setRejectionId(null)}
                                                        className="rounded-xl border px-4 py-2.5 text-sm font-semibold"
                                                    >
                                                        Cancel
                                                    </button>
                                                </div>
                                            </div>
                                        )}
                                    </div>
                                );
                            })}
                        </div>
                    )}

                    {!loading && !readyForApproval && (
                        <p className="rounded-xl bg-amber-50 p-4 text-xs text-amber-800">
                            Driver approval remains blocked until all required documents
                            pass verification.
                        </p>
                    )}
                </div>

                {preview && (
                    <div className="absolute inset-0 z-10 flex flex-col bg-slate-950/95 p-5">
                        <div className="mb-4 flex items-center justify-between text-white">
                            <p className="font-bold">Secure Document Preview</p>
                            <button
                                type="button"
                                onClick={() => setPreview(null)}
                                aria-label="Close preview"
                                className="rounded-xl bg-white/15 p-3"
                            >
                                <X size={20} />
                            </button>
                        </div>
                        <div className="flex min-h-0 flex-1 items-center justify-center">
                            <img
                                src={preview.url}
                                alt="Driver verification document"
                                referrerPolicy="no-referrer"
                                className="max-h-full max-w-full object-contain"
                            />
                        </div>
                        <p className="mt-3 text-center text-xs text-white/65">
                            Temporary signed document access.
                            Link expires after {preview.expiresIn} seconds.
                        </p>
                    </div>
                )}
            </section>
        </div>
    );
}
